import { describe, expect, it } from 'vitest';
import goldenFile from './jarvis-lattice.golden.json';
import {
  detailFull, detailMinimal, detailReduced, getLatticeModel, latticeDetailForSize, latticePulse, makeLatticeScene,
  pulsePeriod, type LatticeDetail,
} from './jarvis-lattice';
import type { OrbFrame, OrbMotionFrame } from './jarvis-orb-motion';

type Golden = {
  seed: number;
  model: {
    nodes: number[][];
    edges: number[][];
    clusters: number[][];
    ignitions: { period: number; offset: number; hops: number[] }[];
    routes: { nodes: number[]; edges: number[]; forward: boolean[]; period: number; offset: number; hopDuration: number }[];
  };
  scenes: {
    name: string;
    detail: LatticeDetail;
    time: number;
    flow: number;
    motion: OrbMotionFrame;
    edges: number[][];
    dots: number[][];
    signals: number[][];
    heart: number[];
    outerGain: number;
  }[];
};

// The golden file is generated by the Swift implementation and rounded to six decimals.
const golden = goldenFile as unknown as Golden;
const tolerance = 2e-5;

function expectClose(actual: number[], expected: number[], label: string) {
  expect(actual.length, label).toBe(expected.length);
  actual.forEach((value, index) => {
    if (Math.abs(value - expected[index]!) >= tolerance) {
      throw new Error(`${label}[${index}]: ${value} differs from ${expected[index]}`);
    }
  });
}

describe('lattice topology', () => {
  const model = getLatticeModel();

  it('grows the same nodes, connections, clusters, sequences and routes as the Swift lattice', () => {
    expect(model.nodes).toHaveLength(golden.model.nodes.length);
    model.nodes.forEach((node, index) => {
      expectClose(
        [node.x, node.y, node.z, node.layer, node.radius, node.cluster, node.warmth, node.size, node.rank, node.phase],
        golden.model.nodes[index]!, `node ${index}`,
      );
    });
    expect(model.edges).toHaveLength(golden.model.edges.length);
    model.edges.forEach((edge, index) => {
      expectClose([edge.a, edge.b, edge.bow, edge.rank], golden.model.edges[index]!, `edge ${index}`);
    });
    expect(model.clusters).toHaveLength(golden.model.clusters.length);
    model.clusters.forEach((cluster, index) => {
      expectClose([...cluster.amplitude, ...cluster.speed, ...cluster.phase], golden.model.clusters[index]!, `cluster ${index}`);
    });
    expect(model.ignitions).toHaveLength(golden.model.ignitions.length);
    model.ignitions.forEach((ignition, index) => {
      const expected = golden.model.ignitions[index]!;
      expectClose([ignition.period, ignition.offset], [expected.period, expected.offset], `ignition ${index}`);
      expect([...ignition.hops]).toEqual(expected.hops);
    });
    expect(model.routes).toHaveLength(golden.model.routes.length);
    model.routes.forEach((route, index) => {
      const expected = golden.model.routes[index]!;
      expect(route.nodes).toEqual(expected.nodes);
      expect(route.edges).toEqual(expected.edges);
      expect(route.forward).toEqual(expected.forward);
      expectClose([route.period, route.offset, route.hopDuration], [expected.period, expected.offset, expected.hopDuration], `route ${index}`);
    });
  });

  it('stays airy: a hundred or so nodes joined by a few hundred long connections', () => {
    expect(model.nodes.length).toBeLessThan(150);
    expect(model.edges.length).toBeGreaterThan(150);
    expect(model.edges.length).toBeLessThan(400);
  });

  it('is built once and shared', () => {
    expect(getLatticeModel()).toBe(model);
    expect(golden.seed).toBe(1834);
  });
});

describe('lattice scene', () => {
  const model = getLatticeModel();

  for (const entry of golden.scenes) {
    it(`poses the ${entry.name} frame like Swift`, () => {
      const frame: OrbFrame = { motion: entry.motion, time: entry.time, flow: entry.flow };
      const scene = makeLatticeScene(model, frame, entry.detail);
      expect(scene.edges).toHaveLength(entry.edges.length);
      scene.edges.forEach((edge, index) => {
        expectClose(
          [edge.ax, edge.ay, edge.cx, edge.cy, edge.bx, edge.by, edge.warmth, edge.alpha, edge.light],
          entry.edges[index]!, `${entry.name} edge ${index}`,
        );
      });
      expect(scene.dots).toHaveLength(entry.dots.length);
      scene.dots.forEach((dot, index) => {
        expectClose([dot.x, dot.y, dot.radius, dot.warmth, dot.alpha, dot.halo], entry.dots[index]!, `${entry.name} dot ${index}`);
      });
      expect(scene.signals).toHaveLength(entry.signals.length);
      scene.signals.forEach((signal, index) => {
        expectClose(
          [signal.x, signal.y, signal.radius, signal.warmth, signal.alpha, signal.halo],
          entry.signals[index]!, `${entry.name} signal ${index}`,
        );
      });
      expectClose(
        [scene.heart.x, scene.heart.y, scene.heart.radius, scene.heart.intensity, scene.heart.heat],
        entry.heart, `${entry.name} heart`,
      );
      expectClose([scene.outerGain], [entry.outerGain], `${entry.name} outerGain`);
    });
  }

  it('keeps hubs and the strongest connections at small sizes', () => {
    const frame: OrbFrame = {
      motion: { awake: 1, ignite: 1, wave: 1, waveStrength: 0, surge: 0, listen: 0, think: 0, tool: 0, speak: 0, speech: 0, input: 0 },
      time: 3, flow: 3,
    };
    const full = makeLatticeScene(model, frame, detailFull);
    const reduced = makeLatticeScene(model, frame, detailReduced);
    const minimal = makeLatticeScene(model, frame, detailMinimal);
    expect(minimal.dots.length).toBeGreaterThan(30);
    expect(minimal.dots.length).toBeLessThan(reduced.dots.length);
    expect(reduced.dots.length).toBeLessThan(full.dots.length);
    expect(minimal.edges.length).toBeLessThan(full.edges.length);
    expect(latticeDetailForSize(18)).toBe(detailMinimal);
    expect(latticeDetailForSize(56)).toBe(detailReduced);
    expect(latticeDetailForSize(120)).toBe(detailFull);
  });
});

describe('heart pulse', () => {
  it('beats once every 1.6 seconds', () => {
    expect(pulsePeriod).toBe(1.6);
    for (const time of [0.3, 1.1, 2.9]) {
      expect(latticePulse(time + pulsePeriod)).toBeCloseTo(latticePulse(time), 9);
    }
    const peak = latticePulse(0.16 * pulsePeriod);
    expect(peak).toBeGreaterThan(0.95);
    expect(latticePulse(0.7 * pulsePeriod)).toBeLessThan(0.1);
  });
});
