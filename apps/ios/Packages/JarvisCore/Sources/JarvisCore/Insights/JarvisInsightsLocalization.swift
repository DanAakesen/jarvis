public enum JarvisInsightsLocalization {
    public static func string(
        _ key: JarvisInsightsLocalizationKey,
        language: JarvisAppLanguage = .default
    ) -> String {
        guard let url = Bundle.module.url(forResource: language.rawValue, withExtension: "lproj"),
              let bundle = Bundle(url: url) else {
            return key.rawValue
        }
        return bundle.localizedString(forKey: key.rawValue, value: key.rawValue, table: "JarvisInsights")
    }

    public static func format(
        _ key: JarvisInsightsLocalizationKey,
        language: JarvisAppLanguage = .default,
        _ arguments: CVarArg...
    ) -> String {
        String(format: string(key, language: language), locale: language.locale, arguments: arguments)
    }
}
